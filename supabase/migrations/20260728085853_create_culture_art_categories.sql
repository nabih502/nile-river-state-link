CREATE TABLE IF NOT EXISTS culture_art_categories (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE,
  title text NOT NULL DEFAULT '',
  icon text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  activities text NOT NULL DEFAULT '',
  published boolean NOT NULL DEFAULT true,
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE culture_art_categories ENABLE ROW LEVEL SECURITY;

CREATE POLICY "select_art_categories_anon" ON culture_art_categories
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "insert_art_categories_auth" ON culture_art_categories
  FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "update_art_categories_auth" ON culture_art_categories
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "delete_art_categories_auth" ON culture_art_categories
  FOR DELETE TO authenticated USING (true);

